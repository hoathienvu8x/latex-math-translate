size_t utf8_charlen(unsigned char c) {
  if (c < 0x80) return 1;
  if ((c >> 5) == 0x6) return 2;
  if ((c >> 4) == 0xe) return 3;
  if ((c >> 3) == 0x1e) return 4;
  return 1;
}
unsigned int utf8_codepoint(const char *p, size_t *len) {
  unsigned char c = (unsigned char)p[0];
  unsigned int codepoint = 0;
  *len = utf8_charlen(c);
  switch (*len) {
    case 1: {
      codepoint = c;
      break;
    }
    case 2: {
      codepoint = ((c & 0x1f) << 6) | (p[1] & 0x3f);
      break;
    }
    case 3: {
      codepoint = ((c & 0x0f) << 12) | ((p[1] & 0x3f) << 6) | (p[2] & 0x3f);
      break;
    }
    case 4: {
      codepoint = (
        ((c & 0x07) << 18) | ((p[1] & 0x3f) << 12) |
        ((p[2] & 0x3f) << 6) | (p[3] & 0x3f)
      );
      break;
    }
  }
  return codepoint;
}
static size_t utf8_encode(unsigned int cp, char *out) {
  if (cp <= 0x7f) {
    out[0] = cp; return 1;
  } else if (cp <= 0x7ff) {
    out[0] = 0xc0 | ((cp >> 6) & 0x1f);
    out[1] = 0x80 | (cp & 0x3f);
    return 2;
  } else if (cp <= 0xffff) {
    out[0] = 0xe0 | ((cp >> 12) & 0x0f);
    out[1] = 0x80 | ((cp >> 6) & 0x3f);
    out[2] = 0x80 | (cp & 0x3f);
    return 3;
  } else if (cp <= 0x10ffff) {
    out[0] = 0xf0 | ((cp >> 18) & 0x07);
    out[1] = 0x80 | ((cp >> 12) & 0x3f);
    out[2] = 0x80 | ((cp >> 6) & 0x3f);
    out[3] = 0x80 | (cp & 0x3f);
    return 4;
  }
  return 0;
}

static unsigned int utf8_codepoint_tolower(unsigned int cp) {
  int i;
  for (i = 0; utf8_lower_ranges[i].end != 0; i++) {
    if (cp >= utf8_lower_ranges[i].start && cp <= utf8_lower_ranges[i].end) {
      return cp + utf8_lower_ranges[i].delta;
    }
  }
  return cp;
}
int utf8_tolower(const char *input, size_t len, char **out, size_t *sz) {
  struct iobuf_t io;
  const char *p, *end;
  if (!input || len == 0 || !out || iobuf_init(&io, len)) return -1;

  p = input, end = input + len;

  while (p < end) {
    size_t clen, n;
    char tmp[4];    
    unsigned int cp = utf8_codepoint(p, &clen);
    if (clen <= 0) {
      goto clean_up;
    }
    cp = utf8_codepoint_tolower(cp);
    n = utf8_encode(cp, tmp);
    if (n <= 0) {
      goto clean_up;
    }
    if (iobuf_append(&io, tmp, n) == 0) {
      goto clean_up;
    }
    p += clen;
  }
  *out = (char *)io.buf;
  if (sz) *sz = io.len;
  return 0;

clean_up:
  iobuf_free(&io);
  return -1;
}
